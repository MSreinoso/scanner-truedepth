import Foundation
import simd

/// Exporter for Stanford Polygon File Format (.PLY) supporting colored point clouds and meshes.
/// Fully compatible with CloudCompare, MeshLab, Blender, and Open3D.
class PLYExporter {
    enum PLYError: Error, LocalizedError {
        case emptyData
        case writeFailed(String)
        
        var errorDescription: String? {
            switch self {
            case .emptyData: return "No hay datos de nube de puntos para exportar."
            case .writeFailed(let msg): return "Error al guardar archivo PLY: \(msg)"
            }
        }
    }
    
    /// Exports colored point cloud and mesh faces to Binary Little-Endian PLY.
    static func exportToBinaryPLY(mesh: Mesh3D, filename: String = "TrueDepth_ColorScan.ply") throws -> URL {
        let vertexCount = mesh.triangles.count * 3
        guard vertexCount > 0 else {
            throw PLYError.emptyData
        }
        
        let tempDir = FileManager.default.temporaryDirectory
        let fileURL = tempDir.appendingPathComponent(filename)
        
        // Construct PLY Header
        let faceCount = mesh.triangles.count
        var header = "ply\n"
        header += "format binary_little_endian 1.0\n"
        header += "comment Generated by TrueDepth 3D Scanner - Sub-millimeter Rigidity\n"
        header += "element vertex \(vertexCount)\n"
        header += "property float x\n"
        header += "property float y\n"
        header += "property float z\n"
        header += "property float nx\n"
        header += "property float ny\n"
        header += "property float nz\n"
        header += "property uchar red\n"
        header += "property uchar green\n"
        header += "property uchar blue\n"
        header += "element face \(faceCount)\n"
        header += "property list uchar int vertex_indices\n"
        header += "end_header\n"
        
        guard var data = header.data(using: .utf8) else {
            throw PLYError.writeFailed("No se pudo codificar la cabecera PLY.")
        }
        
        // Write Binary Vertices (X, Y, Z in mm, Normal, RGB)
        for tri in mesh.triangles {
            let vertices = [
                (pos: tri.v1, col: tri.c1),
                (pos: tri.v2, col: tri.c2),
                (pos: tri.v3, col: tri.c3)
            ]
            
            for v in vertices {
                // X, Y, Z (mm)
                var x = v.pos.x * 1000.0
                var y = v.pos.y * 1000.0
                var z = v.pos.z * 1000.0
                withUnsafeBytes(of: &x) { data.append(contentsOf: $0) }
                withUnsafeBytes(of: &y) { data.append(contentsOf: $0) }
                withUnsafeBytes(of: &z) { data.append(contentsOf: $0) }
                
                // Normal vector
                var nx = tri.normal.x
                var ny = tri.normal.y
                var nz = tri.normal.z
                withUnsafeBytes(of: &nx) { data.append(contentsOf: $0) }
                withUnsafeBytes(of: &ny) { data.append(contentsOf: $0) }
                withUnsafeBytes(of: &nz) { data.append(contentsOf: $0) }
                
                // RGB
                var r = v.col.x
                var g = v.col.y
                var b = v.col.z
                data.append(r)
                data.append(g)
                data.append(b)
            }
        }
        
        // Write Faces (3 indices per face)
        var faceIndex: Int32 = 0
        let listCount: UInt8 = 3
        for _ in 0..<faceCount {
            data.append(listCount)
            var i1 = faceIndex
            var i2 = faceIndex + 1
            var i3 = faceIndex + 2
            withUnsafeBytes(of: &i1) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &i2) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &i3) { data.append(contentsOf: $0) }
            faceIndex += 3
        }
        
        do {
            try data.write(to: fileURL, options: .atomic)
            return fileURL
        } catch {
            throw PLYError.writeFailed(error.localizedDescription)
        }
    }
}
