import Foundation
import simd

class STLExporter {
    enum STLError: Error, LocalizedError {
        case emptyMesh
        case fileWriteFailed(String)
        
        var errorDescription: String? {
            switch self {
            case .emptyMesh:
                return "La malla generada está vacía. Acércate al objeto."
            case .fileWriteFailed(let msg):
                return "No se pudo guardar el archivo STL: \(msg)"
            }
        }
    }
    
    static func exportToBinarySTL(mesh: Mesh3D, filename: String = "TrueDepth_Scan.stl") throws -> URL {
        guard !mesh.triangles.isEmpty else {
            throw STLError.emptyMesh
        }
        
        let tempDir = FileManager.default.temporaryDirectory
        let fileURL = tempDir.appendingPathComponent(filename)
        
        var data = Data()
        let headerText = "Binary STL generated by TrueDepth iOS 3D Scanner"
        var header = [UInt8](repeating: 0, count: 80)
        let headerBytes = Array(headerText.utf8.prefix(80))
        for (i, byte) in headerBytes.enumerated() {
            header[i] = byte
        }
        data.append(contentsOf: header)
        
        var triangleCount = UInt32(mesh.triangles.count).littleEndian
        withUnsafeBytes(of: &triangleCount) { data.append(contentsOf: $0) }
        
        var attributeByteCount: UInt16 = 0
        
        for triangle in mesh.triangles {
            var nx = triangle.normal.x
            var ny = triangle.normal.y
            var nz = triangle.normal.z
            withUnsafeBytes(of: &nx) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &ny) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &nz) { data.append(contentsOf: $0) }
            
            var v1x = triangle.v1.x * 1000.0
            var v1y = triangle.v1.y * 1000.0
            var v1z = triangle.v1.z * 1000.0
            withUnsafeBytes(of: &v1x) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v1y) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v1z) { data.append(contentsOf: $0) }
            
            var v2x = triangle.v2.x * 1000.0
            var v2y = triangle.v2.y * 1000.0
            var v2z = triangle.v2.z * 1000.0
            withUnsafeBytes(of: &v2x) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v2y) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v2z) { data.append(contentsOf: $0) }
            
            var v3x = triangle.v3.x * 1000.0
            var v3y = triangle.v3.y * 1000.0
            var v3z = triangle.v3.z * 1000.0
            withUnsafeBytes(of: &v3x) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v3y) { data.append(contentsOf: $0) }
            withUnsafeBytes(of: &v3z) { data.append(contentsOf: $0) }
            
            withUnsafeBytes(of: &attributeByteCount) { data.append(contentsOf: $0) }
        }
        
        do {
            try data.write(to: fileURL)
            return fileURL
        } catch {
            throw STLError.fileWriteFailed(error.localizedDescription)
        }
    }
}
